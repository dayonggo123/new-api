// ---- Shared types ----

type SubscriptionPlanDTO struct {
	Plan             model.SubscriptionPlan `json:"plan"`
	OriginalPrice    float64                `json:"original_price"`
	DiscountedPrice  float64                `json:"discounted_price"`
	GroupRatio       float64                `json:"group_ratio"`
	DiscountPercent  float64                `json:"discount_percent"` // 0-100
}

func buildSubscriptionPlanDTOs(plans []model.SubscriptionPlan, userId int) []SubscriptionPlanDTO {
	result := make([]SubscriptionPlanDTO, 0, len(plans))
	for _, p := range plans {
		// 套餐对应的分组倍率（基于 UpgradeGroup，与后台「分组相关设置」保持一致）
		planGroupRatio := ratio_setting.GetGroupRatio(p.UpgradeGroup)
		if planGroupRatio <= 0 {
			planGroupRatio = 1.0
		}

		// GroupRatio 仅用于展示该套餐升级目标分组的模型调用倍率，
		// 订阅价格本身不受分组倍率影响，始终使用套餐配置的原始价格
		result = append(result, SubscriptionPlanDTO{
			Plan:            p,
			OriginalPrice:   p.PriceAmount,
			DiscountedPrice: p.PriceAmount,
			GroupRatio:      planGroupRatio,
			DiscountPercent: 0,
		})
	}
	return result
}

// GetSubscriptionPlans returns all enabled plans with group-discounted prices.
func GetSubscriptionPlans(c *gin.Context) {
	var plans []model.SubscriptionPlan
	if err := model.DB.Where("enabled = ?", true).Order("sort_order desc, id desc").Find(&plans).Error; err != nil {
		common.ApiError(c, err)
		return
	}

	userId := 0
	if id, exists := c.Get("id"); exists {
		userId = id.(int)
	}

	result := buildSubscriptionPlanDTOs(plans, userId)
	common.ApiSuccess(c, result)
}

// GetSubscriptionGroupDiscount returns the current user's group info.
// Note: group_ratio is the model-call price ratio, NOT a subscription discount.
func GetSubscriptionGroupDiscount(c *gin.Context) {
	userId := c.GetInt("id")
	userGroup, _ := model.GetUserGroup(userId, false)
	groupRatio := ratio_setting.GetGroupRatio(userGroup)

	common.ApiSuccess(c, gin.H{
		"user_group":       userGroup,
		"group_ratio":      groupRatio,
		"discount_percent": 0,
	})
}

type BillingPreferenceRequest struct {
	BillingPreference string `json:"billing_preference"`
}

func GetSubscriptionSelf(c *gin.Context) {
	userId := c.GetInt("id")
	settingMap, _ := model.GetUserSetting(userId, false)
	pref := common.NormalizeBillingPreference(settingMap.BillingPreference)

	// Get all subscriptions (including expired)
	allSubscriptions, err := model.GetAllUserSubscriptions(userId)
	if err != nil {
		allSubscriptions = []model.SubscriptionSummary{}
	}

	// Get active subscriptions for backward compatibility
	activeSubscriptions, err := model.GetAllActiveUserSubscriptions(userId)
	if err != nil {
		activeSubscriptions = []model.SubscriptionSummary{}
	}

	common.ApiSuccess(c, gin.H{
		"billing_preference": pref,
		"subscriptions":      activeSubscriptions, // all active subscriptions
		"all_subscriptions":  allSubscriptions,    // all subscriptions including expired
	})
}

func UpdateSubscriptionPreference(c *gin.Context) {
	userId := c.GetInt("id")
	var req BillingPreferenceRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		common.ApiErrorMsg(c, "参数错误")
		return
	}
	pref := common.NormalizeBillingPreference(req.BillingPreference)

	user, err := model.GetUserById(userId, true)
	if err != nil {
		common.ApiError(c, err)
		return
	}
	current := user.GetSetting()
	current.BillingPreference = pref
	user.SetSetting(current)
	if err := user.Update(false); err != nil {
		common.ApiError(c, err)
		return
	}
	common.ApiSuccess(c, gin.H{"billing_preference": pref})
}

